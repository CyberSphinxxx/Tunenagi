#!/usr/bin/env python3
"""Formatting gate: enforce the repository's documented text-style rules.

Rules (documented in OPERATIONS/GIT_CONVENTIONS.md, enforced here):
  F1 tab character used for indentation
  F2 trailing whitespace
  F3 file does not end with exactly one newline
  F4 carriage return in the stored content (the repository stores LF in the index)
  F5 line longer than --max-line characters (code/script/config files only)

**What is checked:** the content git *stores* for tracked files (`git show :<path>`), not
the bytes on disk. A Windows checkout with `core.autocrlf=true` legitimately has CRLF in
the working tree while the index is LF, and failing every file for that would make the
gate useless. Files passed with `--paths` are read from disk, which is how an author
checks work that is not staged yet.

F1-F4 apply to every tracked text file. F5 applies to code, script and configuration
files; Markdown, JSON, XML and plain text are exempt because single-line XML string
resources and Markdown tables are legitimately long. F5 is additionally waived for the
pre-existing compact harness scripts and the generated Gradle wrapper, listed in
[LENGTH_EXEMPT] - the list may only shrink, never grow to admit new code.

`--self-test` builds a temporary tree that violates every rule and asserts each is caught
while a clean file passes: a gate that cannot fail is not a gate.
"""
import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Extensions that get the full rule set, including the line-length limit.
CODE_SUFFIXES = {
    ".kt", ".kts", ".java", ".gradle", ".py", ".sh", ".ps1", ".bat", ".cmd",
    ".toml", ".properties", ".pro",
}
# Text files that get F1-F4 but not the line-length rule.
TEXT_SUFFIXES = {".md", ".json", ".xml", ".txt", ".gitattributes", ".gitignore", ""}
# Files that are not text and must never be scanned.
SKIP_SUFFIXES = {
    ".png", ".jpg", ".jpeg", ".webp", ".gif", ".ico", ".svg", ".jar", ".zip",
    ".apk", ".aab", ".so", ".dex", ".bin", ".exe", ".dll", ".keystore", ".jks",
    ".p12", ".pem", ".key", ".lock",
}
SKIP_NAMES = {"gradle-wrapper.jar"}

# Machine-written files. Room emits its schema JSON at build time and does not end the file with a
# newline; hand-editing those files to satisfy a text rule would be wrong twice over (the change is
# lost on the next build, and a schema should never be edited by hand). The exclusion is by path and
# covers no hand-written source: every Kotlin, Gradle, script and documentation file is still
# checked. Recorded in the phase-01 audit rather than added quietly.
GENERATED_DIRS = ("core/schemas/",)

# Pre-existing harness scripts are compact by design and reformatting a script that
# enforces evidence requires an independent audit, so the waiver is recorded loudly here
# rather than by weakening the rule. gradlew/gradlew.bat are generated by Gradle.
LENGTH_EXEMPT = {
    "SCRIPTS/loop_driver.py",
    "SCRIPTS/run_check.py",
    "SCRIPTS/taskctl.py",
    "SCRIPTS/validate_package.py",
    "gradlew",
    "gradlew.bat",
}

DEFAULT_MAX_LINE = 140


def tracked_files():
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, stdout=subprocess.PIPE, check=True
    ).stdout
    return [name for name in out.decode("utf8").split("\0") if name]


_PREFIX = None


def checkout_prefix():
    """`git show :<path>` resolves paths against the repository root, not the working
    directory, so the kit's checkout prefix has to be prepended. Getting this wrong makes
    every lookup fail silently, which would look exactly like a clean repository."""
    global _PREFIX
    if _PREFIX is None:
        out = subprocess.run(
            ["git", "rev-parse", "--show-prefix"], cwd=ROOT,
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True,
        ).stdout
        _PREFIX = out.decode("utf8").strip()
    return _PREFIX


def stored_bytes(name):
    """Content git would commit for this path, or None when it is not tracked."""
    proc = subprocess.run(
        ["git", "show", f":{checkout_prefix()}{name}"], cwd=ROOT, stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL, check=False,
    )
    return proc.stdout if proc.returncode == 0 else None


def is_generated(name):
    """True for paths written by a build tool rather than by a person."""
    normalized = name.replace("\\", "/")
    return any(normalized.startswith(prefix) or f"/{prefix}" in normalized for prefix in GENERATED_DIRS)


def classify(name, explicit):
    """Returns the rule set for a path: 'code', 'text', or None to skip.

    Explicitly requested paths are always scanned as text even when their extension is
    unknown, so `--paths` can never silently skip a file the caller asked about.
    """
    if Path(name).name in SKIP_NAMES or is_generated(name):
        return None
    suffix = Path(name).suffix.lower()
    if suffix in SKIP_SUFFIXES:
        return None
    if suffix in CODE_SUFFIXES:
        return "code"
    if suffix in TEXT_SUFFIXES:
        return "text"
    return "text" if explicit else None


def check_bytes(raw, kind, max_line):
    """Returns a list of (rule, line_number, message) for one file's content."""
    problems = []
    if b"\r" in raw:
        for index, chunk in enumerate(raw.split(b"\n"), start=1):
            if chunk.endswith(b"\r"):
                problems.append(("F4", index, "carriage return in stored content; the index stores LF"))
                break

    if not raw:
        return problems
    if not raw.endswith(b"\n"):
        problems.append(("F3", 0, "file does not end with a newline"))
    elif raw.endswith(b"\n\n"):
        problems.append(("F3", raw.count(b"\n"), "file ends with a blank line"))

    for index, line in enumerate(raw.decode("utf8", "replace").split("\n"), start=1):
        body = line.rstrip("\r")
        if "\t" in body:
            problems.append(("F1", index, "tab character"))
        if body != body.rstrip(" \t"):
            problems.append(("F2", index, "trailing whitespace"))
        if kind == "code" and max_line is not None and len(body) > max_line:
            problems.append(("F5", index, f"line is {len(body)} characters (limit {max_line})"))
    return problems


def run(files, max_line, explicit=False):
    findings = []
    checked = 0
    for name in files:
        kind = classify(name, explicit)
        if kind is None:
            continue
        raw = None
        if not explicit:
            raw = stored_bytes(name)
        else:
            path = ROOT / name
            raw = path.read_bytes() if path.is_file() else None
        if raw is None:
            continue
        checked += 1
        limit = None if name in LENGTH_EXEMPT else max_line
        for rule, line, message in check_bytes(raw, kind, limit):
            findings.append((name, rule, line, message))
    if checked == 0:
        print("WARNING: no files were readable to check")
    return checked, findings


def self_test():
    """Builds files that break every rule and asserts that each one is caught."""
    expectations = {
        "bad_tabs.kt": "F1",
        "bad_trailing.kt": "F2",
        "bad_no_eol.kt": "F3",
        "bad_crlf.kt": "F4",
        "bad_long.kt": "F5",
    }
    failures = []
    with tempfile.TemporaryDirectory(prefix="tunenagi-format-") as tmp:
        base = Path(tmp)
        (base / "bad_tabs.kt").write_bytes(b"fun main() {\n\tprintln(1)\n}\n")
        (base / "bad_trailing.kt").write_bytes(b"val x = 1   \n")
        (base / "bad_no_eol.kt").write_bytes(b"val x = 1")
        (base / "bad_crlf.kt").write_bytes(b"val x = 1\r\nval y = 2\r\n")
        (base / "bad_long.kt").write_bytes(("val x = " + "1" * 200 + "\n").encode())
        (base / "good.kt").write_bytes(b"val x = 1\nval y = 2\n")
        (base / "long.md").write_bytes(("# " + "x" * 300 + "\n").encode())

        for name, expected in expectations.items():
            found = check_bytes((base / name).read_bytes(), "code", DEFAULT_MAX_LINE)
            rules = {rule for rule, _, _ in found}
            if expected not in rules:
                failures.append(f"{name} did not report {expected} (reported {sorted(rules)})")
        if check_bytes((base / "good.kt").read_bytes(), "code", DEFAULT_MAX_LINE):
            failures.append("good.kt was reported as dirty")
        if check_bytes((base / "long.md").read_bytes(), "text", DEFAULT_MAX_LINE):
            failures.append("long.md should be exempt from the line-length rule")
        waived = check_bytes((base / "bad_long.kt").read_bytes(), "code", None)
        if [rule for rule, _, _ in waived]:
            failures.append("a waived file should still skip only the length rule")

        if failures:
            for item in failures:
                print(f"SELF-TEST FAIL: {item}")
            return 1
    print(
        "PASS: format gate detects tabs, trailing whitespace, missing final newline, "
        "CRLF and over-long lines; a clean file and a long Markdown line pass."
    )
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--paths", nargs="*", help="Files to check from disk instead of the stored content of every tracked file.")
    parser.add_argument("--max-line", type=int, default=DEFAULT_MAX_LINE)
    parser.add_argument("--self-test", action="store_true", help="Verify the gate can actually fail.")
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    explicit = bool(args.paths)
    files = args.paths if explicit else tracked_files()
    checked, findings = run(files, args.max_line, explicit=explicit)

    for name, rule, line, message in findings:
        location = f"{name}:{line}" if line else name
        print(f"{location}: {rule} {message}")
    print(f"checked {checked} file(s), {len(findings)} problem(s)")
    if findings:
        print("FAIL: formatting gate found problems (see OPERATIONS/GIT_CONVENTIONS.md)")
        return 2
    print("PASS: formatting gate clean")
    return 0


if __name__ == "__main__":
    sys.exit(main())
