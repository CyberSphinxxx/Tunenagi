#!/usr/bin/env python3
"""Tunenagi JSON task state controller. No dependencies outside stdlib."""
import argparse
import datetime as dt
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
TASKS=ROOT/'STATE/tasks.json'
AUDITS=ROOT/'STATE/audits'
DEFECTS=ROOT/'STATE/defects.json'
STATUSES={'todo','in_progress','verified','blocked'}

def now(): return dt.datetime.now(dt.timezone.utc).isoformat(timespec='seconds')
def read(): return json.loads(TASKS.read_text(encoding='utf8'))
def write(data):
    fd, name=tempfile.mkstemp(prefix='.tasks-',dir=TASKS.parent)
    try:
        with os.fdopen(fd,'w',encoding='utf8') as f:
            json.dump(data,f,indent=2,ensure_ascii=False);f.write('\n');f.flush();os.fsync(f.fileno())
        os.replace(name,TASKS)
    finally:
        if os.path.exists(name):os.unlink(name)

def defect_data():return json.loads(DEFECTS.read_text(encoding='utf8'))

def atomic_json(path,data):
    fd,name=tempfile.mkstemp(prefix='.state-',dir=path.parent)
    try:
        with os.fdopen(fd,'w',encoding='utf8') as f:
            json.dump(data,f,indent=2,ensure_ascii=False);f.write('\n');f.flush();os.fsync(f.fileno())
        os.replace(name,path)
    finally:
        if os.path.exists(name):os.unlink(name)

def open_severe(through=None):
    return [d for d in defect_data()['items'] if d['status']=='open' and d['severity'] in {'Critical','High'} and (through is None or d['phase']<=through)]

def invalidate_from(data,phase):
    for p in phases(data):
        if p>=phase:
            cert=AUDITS/f'phase-{p}-pass.json'
            if cert.exists():
                target=cert.with_name(f'phase-{p}-invalidated-{dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")}.json')
                cert.rename(target)

def task(data,ident):
    t=next((x for x in data['tasks'] if x['id']==ident),None)
    if not t: raise ValueError('Unknown task '+ident)
    return t

def phases(data): return sorted({x['phase'] for x in data['tasks']})
def previous_audited(data,phase):
    prev=[x for x in phases(data) if x<phase]
    return all((AUDITS/f'phase-{p}-pass.json').is_file() for p in prev)
def ready(data):
    verified={x['id'] for x in data['tasks'] if x['status']=='verified'}
    return [x for x in data['tasks'] if x['status'] in {'todo','in_progress'} and all(d in verified for d in x['deps']) and previous_audited(data,x['phase'])]

def summary(data):
    print('Tunenagi P0 task state')
    print(f'OPEN Critical/High defects: {len(open_severe())} (details: STATE/defects.json)')
    for p in phases(data):
        tt=[t for t in data['tasks'] if t['phase']==p]
        counts={s:sum(t['status']==s for t in tt) for s in STATUSES}
        print(f"phase {p}: {counts['verified']}/{len(tt)} verified | {counts['in_progress']} active | {counts['blocked']} blocked | audit {'PASS' if (AUDITS/f'phase-{p}-pass.json').exists() else 'PENDING'}")
    cand=ready(data)
    if cand:print(f"NEXT {cand[0]['id']} {cand[0]['title']}")
    else:
        for p in phases(data):
            tt=[t for t in data['tasks'] if t['phase']==p]
            if all(t['status']=='verified' for t in tt) and not (AUDITS/f'phase-{p}-pass.json').exists():
                print(f'AUDIT REQUIRED: phase {p} (read PROMPTS/02_PHASE_AUDIT.md)');break
        else:print('No runnable tasks: all verified or blocked by dependencies/audits.')

def manifest_ok(path,taskid):
    resolved=path.resolve()
    base=(ROOT/'STATE/evidence'/taskid).resolve()
    if not resolved.is_relative_to(base):raise ValueError('Evidence manifest must be under STATE/evidence/<task>')
    data=json.loads(resolved.read_text(encoding='utf8'))
    if data.get('runner')!='tunenagi-run-check-v1':raise ValueError('Not generated by run_check.py')
    if data.get('task')!=taskid:raise ValueError('Evidence task mismatch')
    if data.get('exitCode')!=0:raise ValueError('Check failed (nonzero exit)')
    argv=data.get('argv')
    if not isinstance(argv,list) or not argv:raise ValueError('No executed command')
    joined=' '.join(argv).strip().lower()
    if joined in {'true','echo','echo ok','printf ok','exit 0'}:raise ValueError('Trivial no-op check rejected')
    log=(ROOT/data['logPath']).resolve()
    if not log.is_relative_to(base) or not log.is_file():raise ValueError('Log missing/escaped evidence directory')
    if hashlib.sha256(log.read_bytes()).hexdigest()!=data.get('logSha256'):
        raise ValueError('Evidence log hash mismatch')
    return data

def relative_existing(path,folder):
    p=Path(path)
    if not p.is_absolute():p=(ROOT/p)
    p=p.resolve()
    if not p.is_relative_to(folder.resolve()):raise ValueError('Artifact must reside in '+str(folder))
    if not p.is_file() or p.stat().st_size==0:raise ValueError('Artifact missing or empty: '+str(p))
    return str(p.relative_to(ROOT))

def do_audit(data,args):
    p=args.phase.zfill(2)
    if p not in phases(data):raise ValueError('No phase '+p)
    ts=[t for t in data['tasks'] if t['phase']==p]
    if not all(t['status']=='verified' for t in ts):raise ValueError('Cannot audit; phase has unverified tasks')
    rp=Path(args.report)
    if not rp.is_absolute():rp=ROOT/rp
    rp=rp.resolve()
    if not rp.is_relative_to(AUDITS.resolve()) or not rp.is_file():raise ValueError('Report must exist under STATE/audits')
    content=rp.read_text(encoding='utf8')
    if open_severe(p):raise ValueError('Open Critical/High defect blocks phase audit')
    if len(content)<800 or not re.search(r'Verdict:\s*PASS\b',content,re.I):raise ValueError('Substantive audit report with Verdict: PASS required')
    if 'STATE/evidence/' not in content or 'Exit code' not in content and 'exit code' not in content.lower():
        raise ValueError('Audit must reference evidence paths and actual exit codes')
    gitsha='UNAVAILABLE'
    try:
        import subprocess
        gitsha=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,stderr=subprocess.DEVNULL,text=True).strip()
    except Exception:pass
    cert=dict(phase=p,result='PASS',auditedUtc=now(),report=str(rp.relative_to(ROOT)),reportSha256=hashlib.sha256(rp.read_bytes()).hexdigest(),gitCommit=gitsha,taskIds=[x['id'] for x in ts],reviewType='independent-evidence-audit')
    AUDITS.mkdir(exist_ok=True)
    (AUDITS/f'phase-{p}-pass.json').write_text(json.dumps(cert,indent=2)+'\n',encoding='utf8')
    print(f'Phase {p} certificate created. Machine checks are NOT a replacement for actual independent audit.')

def main():
    p=argparse.ArgumentParser(description=__doc__)
    sub=p.add_subparsers(dest='action',required=True)
    sub.add_parser('status');sub.add_parser('next')
    q=sub.add_parser('claim');q.add_argument('id')
    q=sub.add_parser('verify');q.add_argument('id');q.add_argument('--evidence',required=True);q.add_argument('--artifact',action='append',default=[])
    q=sub.add_parser('block');q.add_argument('id');q.add_argument('--reason',required=True)
    q=sub.add_parser('reopen');q.add_argument('id');q.add_argument('--reason',required=True)
    q=sub.add_parser('gate');q.add_argument('phase')
    q=sub.add_parser('audit');q.add_argument('phase');q.add_argument('--report',required=True)
    sub.add_parser('defects')
    q=sub.add_parser('defect-add');q.add_argument('--phase',required=True);q.add_argument('--severity',choices=['Critical','High','Medium','Low'],required=True);q.add_argument('--task',required=True);q.add_argument('--title',required=True);q.add_argument('--repro',required=True)
    q=sub.add_parser('defect-close');q.add_argument('id');q.add_argument('--evidence',required=True);q.add_argument('--resolution',required=True)
    args=p.parse_args()
    try:
        data=read()
        if args.action=='status':summary(data)
        elif args.action=='next':
            rr=ready(data)
            if rr:print(json.dumps(rr[0],indent=2))
            else:summary(data)
        elif args.action=='defects':
            for d in defect_data()['items']:
                print(f"{d['id']} [{d['severity']}][{d['status']}] phase {d['phase']} {d['title']}")
        elif args.action=='defect-add':
            t=task(data,args.task)
            if t['phase']!=args.phase.zfill(2):raise ValueError('Related task and defect phase mismatch')
            dd=defect_data()
            defectid=f"BUG-{len(dd['items'])+1:04d}"
            dd['items'].append(dict(id=defectid,phase=t['phase'],relatedTask=t['id'],severity=args.severity,status='open',title=args.title,reproduction=args.repro,foundUtc=now(),resolution=None,evidence=None))
            atomic_json(DEFECTS,dd)
            if args.severity in {'Critical','High'}:invalidate_from(data,t['phase'])
            print('Filed',defectid)
        elif args.action=='defect-close':
            dd=defect_data();d=next((x for x in dd['items'] if x['id']==args.id),None)
            if d is None:raise ValueError('Unknown defect')
            if d['status']!='open':raise ValueError('Defect not open')
            ep=Path(args.evidence)
            if not ep.is_absolute():ep=ROOT/ep
            manifest_ok(ep,d['relatedTask'])
            d.update(status='closed',resolution=args.resolution,evidence=str(ep.resolve().relative_to(ROOT)),closedUtc=now())
            atomic_json(DEFECTS,dd)
            print('Closed defect with check evidence',d['id'])
        elif args.action=='claim':
            t=task(data,args.id)
            if t['status']=='verified':raise ValueError('Cannot claim verified task')
            if t not in ready(data):raise ValueError('Task not ready (deps/prior audit missing)')
            t['status']='in_progress';t['notes']=f'Claimed {now()}';write(data);print(f'Claimed {t["id"]}')
        elif args.action=='verify':
            t=task(data,args.id)
            if t['status'] not in {'in_progress','todo'}:raise ValueError('Cannot verify from '+t['status'])
            if t not in ready(data):raise ValueError('Prerequisites not ready')
            ep=Path(args.evidence)
            if not ep.is_absolute():ep=ROOT/ep
            manifest_ok(ep,t['id'])
            folder=ROOT/'STATE/evidence'/t['id']
            artifacts=[relative_existing(x,folder) for x in args.artifact]
            required=set(t.get('evidenceKinds',[]))-{'command'}
            for kind in required:
                if not any(Path(item).name.lower().startswith(kind+'-') for item in artifacts):
                    raise ValueError(f'Task requires {kind}-prefixed evidence artifact in task evidence folder (e.g. {kind}-proof.txt). Auditor checks authenticity.')
            t['status']='verified';t['evidence']=[str(ep.resolve().relative_to(ROOT)),*artifacts];t['notes']=f'Verified via evidence manifest {now()}; semantic review still required.'
            write(data);print(f'Verified metadata for {t["id"]}. Independent audit still required.')
        elif args.action=='block':
            t=task(data,args.id)
            if t['status']=='verified':raise ValueError('Reopen verified task before blocking')
            t['status']='blocked';t['notes']=args.reason;write(data);print('Blocked',args.id)
        elif args.action=='reopen':
            t=task(data,args.id);t['status']='in_progress';t['notes']=args.reason;t['evidence']=[]
            # a reopened earlier phase invalidates it and all downstream phase audits
            invalidate_from(data,t['phase'])
            write(data);print('Reopened',args.id)
        elif args.action=='gate':
            phase=args.phase.zfill(2)
            ts=[t for t in data['tasks'] if t['phase']==phase]
            if not ts:raise ValueError('Unknown phase '+phase)
            bad=[t['id'] for t in ts if t['status']!='verified']
            if open_severe(phase):raise ValueError('Open Critical/High defect blocks phase gate')
            if bad:print('PHASE NOT READY:',', '.join(bad));sys.exit(2)
            print('PHASE TASK METADATA READY for independent audit:',phase)
        elif args.action=='audit':do_audit(data,args)
    except (ValueError,OSError,json.JSONDecodeError,KeyError) as e:
        print('ERROR:',e,file=sys.stderr);sys.exit(2)

if __name__=='__main__':main()
